    // ------------------------------------------------------------------
    // Utilidades
    // ------------------------------------------------------------------

    private String sizeExpr(boolean includeDefines, String macro, int literal) {
        return includeDefines ? macro : String.valueOf(literal);
    }

    /**
     * Byte de atributo ZX Spectrum para el tile 8x8 que empieza en (ty, tx):
     * bit6 BRIGHT, bits5-3 PAPER (0 = negro) y bits2-0 INK. El INK es el color
     * no nulo dominante del bloque (el ZX solo admite 2 colores por bloque 8x8).
     */
    private int zxAttribute(int[][] px, int ty, int tx) {
        int ink = zxTileInk(px, ty, tx);
        int bright = ink >= 8 ? 1 : 0;
        return (bright << 6) | (ink & 0x07);
    }

    private int zxTileInk(int[][] px, int ty, int tx) {
        return dominantColorIndex(px, ty, tx);
    }

    /**
     * Color no nulo dominante (por recuento) del tile 8x8 que empieza en (ty, tx),
     * o 0 si el bloque está vacío. Sirve para el INK del ZX, para el byte de
     * color RAM del C64 y para el byte de atributo del sprite del MSX, que en los
     * tres casos es un único tono por bloque 8x8.
     */
    private int dominantColorIndex(int[][] px, int ty, int tx) {
        int[] counts = new int[16];
        int maxCount = 0;
        int index = 0;
        for (int r = 0; r < 8; r++) {
            int y = ty + r;
            if (y >= px.length) break;
            for (int c = 0; c < 8; c++) {
                int x = tx + c;
                if (x >= px[y].length) break;
                int v = px[y][x] & 0x0F;
                if (v == 0) continue;
                counts[v]++;
                if (counts[v] > maxCount) {
                    maxCount = counts[v];
                    index = v;
                }
            }
        }
        return index;
    }

    private void appendDurations(StringBuilder sb, int frameCount, List<Integer> durationsVbls) {
        for (int i = 0; i < frameCount; i++) {
            int d = (durationsVbls != null && i < durationsVbls.size() && durationsVbls.get(i) != null)
                    ? durationsVbls.get(i) : DEFAULT_DURATION_VBLS;
            sb.append(i == 0 ? "" : ", ").append(d);
        }
    }

    public static String sanitizeSymbol(String raw) {
        String s = raw != null ? raw.trim() : "";
        if (s.isEmpty()) s = "sprite";
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_') {
                sb.append(c);
            } else {
                sb.append('_');
            }
        }
        if (sb.length() == 0) return "sprite";
        if (sb.charAt(0) >= '0' && sb.charAt(0) <= '9') sb.insert(0, '_');
        return sb.toString();
    }
